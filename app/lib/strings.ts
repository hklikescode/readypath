export const STRINGS = { en, es };
export type StringKey = keyof typeof en;

// Spanish names for the family labels in the contacts (the data stays English).
const REL_ES: Record<string, string> = { mom: 'Mamá', mother: 'Mamá', dad: 'Papá', father: 'Papá', grandma: 'Abuela', grandpa: 'Abuelo', aunt: 'Tía', uncle: 'Tío' };
export const localLabel = (label: string, lang: Lang): string =>
  lang === 'es' ? REL_ES[label.trim().toLowerCase()] ?? label : label;

// t('en', 'kidHi', { name: 'Mia' }) -> "Hi Mia!"
export function t(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[lang][key] ?? STRINGS.en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
